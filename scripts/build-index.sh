#!/usr/bin/env bash
# Генератор УКАЗАТЕЛЯ сделанного: что есть, где лежит, чем подтверждено.
#
# Зачем. Наша самая дорогая потеря — не думать плохо, а не помнить. Счёт за одни сутки
# 2026-08-01: спека `LANE-A-FIX-SPEC-native-dispatch-callback-exception.md` от 24 июня была
# РЕАЛИЗОВАНА, а мы собрались писать её заново; счётчик восстановления печатал 360 отказов и 0
# успехов полтора месяца, и никто не прочитал; готовый этаж со сборкой лежал на внешнем диске,
# пока оператор про него не вспомнил.
#
# Ни одна из этих потерь не лечится умом — все лечатся указателем. Заготовки есть и разрознены:
# манифесты этажей, LANE-*-PROGRESS.md, reports/research/*.md, спеки в корне, журналы профилей.
# Не хватало одного файла, с которого начинается любая работа: «делали ли это уже».
#
# Указатель СОБИРАЕТСЯ, а не пишется руками, иначе он устареет через неделю и станет вреднее
# отсутствия — будет выглядеть полным.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
OUT="УКАЗАТЕЛЬ.md"
FLOORS="/Volumes/MacOS 1/MacRunner-ARM64EC-floors"

{
  echo "# УКАЗАТЕЛЬ сделанного"
  echo
  echo "Собран \`scripts/build-index.sh\` — **не править руками**, править источники и пересобрать."
  echo "Обновлён: $(date '+%Y-%m-%d %H:%M')"
  echo
  echo "**Первый шаг любой работы: найти здесь, делали ли это уже.** Трижды за 1 августа мы"
  echo "переоткрывали своё же — спеку от 24 июня, счётчик 360/0, этаж на внешнем диске."
  echo
  echo "## Спеки и планы в корне"
  echo
  for f in *.md; do
    [ -f "$f" ] || continue
    case "$f" in CLAUDE.md|AGENTS.md|README.md|УКАЗАТЕЛЬ.md) continue;; esac
    printf -- "- [%s](%s) — %s\n" "$f" "$f" "$(head -3 "$f" | tr '\n' ' ' | sed 's/^#* *//' | cut -c1-110)"
  done
  echo
  echo "## Этажи (сохранённые сборки)"
  echo
  echo "Проверять \`scripts/floor-verify.sh\` ПЕРЕД тем, как опереться: манифест расходится с дистом молча."
  echo
  if [ -d "$FLOORS" ]; then
    for d in "$FLOORS"/*/; do
      [ -d "$d" ] || continue
      n="$(basename "$d")"
      if [ -f "$d/MANIFEST.md" ]; then
        printf -- "- **%s** — есть манифест: %s\n" "$n" \
          "$(grep -m1 -iE '^\*\*Что это' "$d/MANIFEST.md" 2>/dev/null | cut -c1-120 || echo 'описан')"
      else
        printf -- "- **%s** — ⚠️ БЕЗ МАНИФЕСТА: чем подтверждён и при каком условии повторяется — неизвестно\n" "$n"
      fi
    done
  else
    echo "- каталог этажей недоступен ($FLOORS) — диск не подключён"
  fi
  echo
  echo "## Профили (эталоны с окружением запуска)"
  echo
  for p in profiles/*/; do
    [ -d "$p" ] || continue
    printf -- "- **%s** — %s\n" "$(basename "$p")" \
      "$(grep -m1 -iE 'источник|обновлён' "$p/О-ПРОФИЛЕ.txt" 2>/dev/null | cut -c1-110 || echo 'без описания')"
  done
  echo
  echo "## Исследования и разборы"
  echo
  for f in $(ls -t reports/research/*.md 2>/dev/null | head -40); do
    case "$(basename "$f")" in LANE-*) continue;; esac
    printf -- "- [%s](%s) — %s\n" "$(basename "$f")" "$f" \
      "$(head -3 "$f" | tr '\n' ' ' | sed 's/^#* *//' | cut -c1-100)"
  done
  echo
  echo "## Инструменты проверки"
  echo
  echo "- \`scripts/preflight-run.sh\` — не даёт запустить прогон, не доказав, что гейт включён,"
  echo "  носители развёрнуты во ВСЕХ дистах и маркеры печатаются. Написан после того, как"
  echo "  пятирукавный бисект отработал на ВЫКЛЮЧЕННОЙ функции."
  echo "- \`scripts/floor-verify.sh\` — сверяет этаж с его манифестом и коммитом."
  echo "- \`scripts/build-index.sh\` — пересобирает этот файл."
} > "$OUT"

echo "собран $OUT: $(wc -l < "$OUT" | tr -d ' ') строк"
grep -c 'БЕЗ МАНИФЕСТА' "$OUT" | sed 's/^/этажей без манифеста: /'
